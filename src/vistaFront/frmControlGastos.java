    //metodo para que se muestre los movimientos almacenados
    private void cargarTabla() {

         modeloTabla.setRowCount(0);

        for (int i = 0; i < control.contarMovimientos(); i++) {

            Movimientos m = control.obtenerMovimiento(i);

            String tipo;

            if (m instanceof Ingresos) {
                tipo = "Ingreso";
            } else {
                tipo = "Gasto";
            }

            modeloTabla.addRow(new Object[]{
                m.getDescripcion(),
                m.getCantidad(),
                m.getFecha(),
                tipo
            });
        }

        actualizarTotales();
    }
    private void actualizarTotales() {

        lblIngresos.setText(
                "Total ingresos: $" + control.calcularTotalIngresos()
        );

        lblGastos.setText(
                "Total gastos: $" + control.calcularTotalGastos()
        );

        lblSaldo.setText(
                "Saldo: $" + control.calcularSaldo()
        );

        lblCantidadMovi.setText(
                "Movimientos: " + control.contarMovimientosRecursivo()
        );
    }


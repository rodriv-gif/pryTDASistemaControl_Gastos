    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {

            String descripcion = txtDescripcion.getText();
            float cantidad = Float.parseFloat(txtCantidad.getText());
            String fecha = txtFecha.getText();
            String tipo = cmbTipo.getSelectedItem().toString();

            Movimientos m;

            if (tipo.equals("Ingreso")) {
                m = new Ingresos(descripcion, cantidad, fecha);
            } else {
                m = new Gastos(descripcion, cantidad, fecha);
            }

            control.registrarMovimiento(m);

            cargarTabla();
            limpiarCampos();

            JOptionPane.showMessageDialog(this, "Movimiento registrado");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String descripcion = txtDescripcion.getText();

        Movimientos m = control.buscarMovimiento(descripcion);

        if (m != null) {

            txtCantidad.setText(String.valueOf(m.getCantidad()));
            txtFecha.setText(m.getFecha());

            if (m instanceof Ingresos) {
                cmbTipo.setSelectedItem("Ingreso");
            } else {
                cmbTipo.setSelectedItem("Gasto");
            }

            JOptionPane.showMessageDialog(this, "Movimiento encontrado");

        } else {

            JOptionPane.showMessageDialog(this, "No se encontró");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String descripcion = txtDescripcion.getText();

        boolean eliminado = control.eliminarMovimiento(descripcion);

        if (eliminado) {

            cargarTabla();
            limpiarCampos();

            JOptionPane.showMessageDialog(this, "Movimiento eliminado");

        } else {

            JOptionPane.showMessageDialog(this, "No se encontró el movimiento");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        String descripcion = txtDescripcion.getText();

        try {

            float cantidad = Float.parseFloat(txtCantidad.getText());
            String fecha = txtFecha.getText();
            String tipo = cmbTipo.getSelectedItem().toString();

            Movimientos nuevo;

            if (tipo.equals("Ingreso")) {
                nuevo = new Ingresos(descripcion, cantidad, fecha);
            } else {
                nuevo = new Gastos(descripcion, cantidad, fecha);
            }

            boolean actualizado = control.actualizarMovimiento(descripcion, nuevo);

            if (actualizado) {

                cargarTabla();
                limpiarCampos();

                JOptionPane.showMessageDialog(this, "Movimiento actualizado");

            } else {

                JOptionPane.showMessageDialog(this, "No se encontró el movimiento");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void tblMovimientosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMovimientosMouseClicked
        int fila = tblMovimientos.getSelectedRow();

        if (fila >= 0) {

            txtDescripcion.setText(
                    tblMovimientos.getValueAt(fila, 0).toString()
            );

            txtCantidad.setText(
                    tblMovimientos.getValueAt(fila, 1).toString()
            );

            txtFecha.setText(
                    tblMovimientos.getValueAt(fila, 2).toString()
            );

            cmbTipo.setSelectedItem(
                    tblMovimientos.getValueAt(fila, 3).toString()
            );
        }
    }//GEN-LAST:event_tblMovimientosMouseClicked

